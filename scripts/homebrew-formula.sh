#!/usr/bin/env bash
# Render the Homebrew formula from a verified release payload. Read-only.
# GoReleaser's `brews` generator is deprecated (goreleaser check fails) and its
# casks have no test block, so the formula comes from the signed checksums.
set -euo pipefail

dist=${1:?usage: homebrew-formula.sh DIST [DOWNLOAD_URL]}
version=$(jq -er '.version | select(type == "string" and test("^[0-9]+\\.[0-9]+\\.[0-9]+"))' "$dist/kitbag-update.json")
url=${2:-https://github.com/TomaszJanusz/kitbag/releases/download/v$version}

sum() {
  local name="kitbag_${version}_$1.tar.gz" hash
  hash=$(awk -v name="$name" '$2 == name { print $1 }' "$dist/checksums.txt")
  [[ "$hash" =~ ^[0-9a-f]{64}$ ]] || {
    echo "homebrew-formula: no single checksum for $name" >&2
    return 1
  }
  printf '%s' "$hash"
}

darwin_arm64=$(sum darwin_arm64)
darwin_amd64=$(sum darwin_amd64)
linux_arm64=$(sum linux_arm64)
linux_amd64=$(sum linux_amd64)

cat <<RUBY
# Generated by scripts/homebrew-formula.sh from the signed checksums.txt of
# KitBag $version. Do not edit; the release workflow replaces this file.
class Kitbag < Formula
  desc "Synchronize AI coding agents' global configuration from a Git repository"
  homepage "https://github.com/TomaszJanusz/kitbag"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$url/kitbag_${version}_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$url/kitbag_${version}_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$url/kitbag_${version}_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$url/kitbag_${version}_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    # kitbag resolves bin's symlink and reads the stamp beside the real
    # executable, so self-update defers to brew (docs/self-update.md).
    libexec.install "kitbag"
    (libexec/"kitbag.install-source").write "homebrew\\n"
    bin.install_symlink libexec/"kitbag"
  end

  # Only a missing prerequisite is worth a caveat: Homebrew prints caveats on
  # every install and upgrade. First-run guidance belongs to kitbag itself.
  def caveats
    return if which("git")

    <<~EOS
      KitBag uses Git to fetch and publish your configuration repository.
      Git was not found on your PATH; install it, for example: brew install git
    EOS
  end

  test do
    assert_equal "kitbag #{version}", shell_output("#{bin}/kitbag version --bare").strip
    system bin/"kitbag", "version"
    assert_match "brew upgrade kitbag", shell_output("#{bin}/kitbag self-update")
  end
end
RUBY
