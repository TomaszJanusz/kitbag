package plan

import (
	"errors"
	"io/fs"
	"slices"

	"github.com/TomaszJanusz/kitbag/internal/core/state"
	"github.com/TomaszJanusz/kitbag/internal/platform"
	"github.com/TomaszJanusz/kitbag/internal/target"
)

// Candidate is an unowned destination that already holds what a plan would
// write. Legacy marks agent-config-sync's equivalent rendering (another marker).
type Candidate struct {
	Target state.Target
	Legacy bool
}

// Candidates lists unowned declarations whose destinations already hold the
// desired output: a link whose lexical target is exactly the source or that
// reaches it through declared legacy roots (LinkReaches; link mode),
// an identical copy (copy mode), identical or legacy-equivalent generated bytes,
// and settings that the merge leaves unchanged. It reads only; ownership is
// established by the caller. Unsafe or unsupported destinations are omitted.
func Candidates(fsys platform.FS, req Request) ([]Candidate, error) {
	declarations, err := Declarations(fsys, req)
	if err != nil {
		return nil, err
	}
	b := builder{fsys: fsys, repository: req.Repository, mode: req.Manifest.Mode, machineMode: req.Mode, legacyRoots: slices.Clone(req.LegacyRoots), old: map[string]state.Target{}, desired: map[string]prepared{}, removed: map[string]bool{}}
	for _, previous := range req.State.Targets {
		b.old[previous.Path] = previous
	}
	if err = b.prepare(declarations); err != nil {
		return nil, err
	}
	var result []Candidate
	for _, declaration := range declarations {
		p, eligible := b.unowned(declaration.Path)
		if !eligible {
			continue
		}
		candidate, ok, candidateErr := b.candidate(p)
		if candidateErr != nil {
			return nil, candidateErr
		}
		if ok {
			result = append(result, candidate)
		}
	}
	return result, nil
}

// unowned returns a prepared declaration that adoption may consider.
func (b *builder) unowned(path string) (prepared, bool) {
	p, exists := b.desired[path]
	_, owned := b.old[path]
	return p, exists && !owned && !p.declaration.Preserve && p.declaration.Warning == ""
}

func (b *builder) candidate(p prepared) (Candidate, bool, error) {
	entry, err := Inspect(b.fsys, p.desired.Path)
	if errors.Is(err, fs.ErrInvalid) || entry.Kind == "" {
		return Candidate{}, false, nil
	}
	if err != nil {
		return Candidate{}, false, err
	}
	d := p.desired
	owned := state.Target{Path: d.Path, SourcePath: d.SourcePath, SourceHash: d.SourceHash, Owners: slices.Clone(d.Owners)}
	switch d.Kind {
	case target.Materialized:
		return b.materializedCandidate(d, entry, owned)
	case target.Generated:
		owned.Kind = state.Generated
	case target.Merged:
		owned.Kind = state.Merged
		accepted, mergeErr := b.merge(&p, current{exists: entry.Kind == "file"})
		if mergeErr != nil || !accepted {
			return Candidate{}, false, mergeErr
		}
	}
	return outputCandidate(p.desired, entry, owned)
}

// outputCandidate accepts generated or merged bytes equal to the desired
// output or to agent-config-sync's equivalent rendering of it.
func outputCandidate(d Desired, entry state.Entry, owned state.Target) (Candidate, bool, error) {
	if entry.Kind != "file" || (entry.Hash != d.WrittenHash && entry.Hash != d.LegacyHash) {
		return Candidate{}, false, nil
	}
	owned.WrittenHash = entry.Hash
	return Candidate{Target: owned, Legacy: entry.Hash != d.WrittenHash}, true, nil
}

func (b *builder) materializedCandidate(d Desired, entry state.Entry, owned state.Target) (Candidate, bool, error) {
	owned.WrittenHash = d.SourceHash
	mode := b.machineMode
	if mode == "" || d.Mode == "copy" {
		mode = cmpMode(d.Mode)
	}
	if mode == "link" && entry.Kind == "link" {
		owned.Kind = state.Link
		reaches, err := LinkReaches(b.fsys, d.Path, entry.Link, d.SourcePath, b.legacyRoots)
		return Candidate{Target: owned}, reaches, err
	}
	owned.Kind = state.Copy
	return Candidate{Target: owned}, mode == "copy" && entry.Kind != "link" && entry.Hash == d.SourceHash, nil
}

func cmpMode(declared string) string {
	if declared == "copy" {
		return "copy"
	}
	return "link"
}
