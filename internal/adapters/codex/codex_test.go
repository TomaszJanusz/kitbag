// TestPrompts: Markdown files are copied byte for byte, per_agent.codex wins,
// and other entries are reported unsupported rather than converted.
func TestPrompts(t *testing.T) {
	t.Parallel()
	r := newFixture(t, nil).plan(t, everything)
	for name, source := range map[string]string{
		"review.md":  repository + "/commands/review.md",
		"shared.md":  repository + "/codex-commands/shared.md",
		"build.toml": "",
		"nested":     "",
	} {
		d, ok := find(r.Targets, codexHome+"/prompts/"+name)
		unsupported := strings.Contains(d.Warning, "not a Markdown prompt file")
		if !ok || d.SourcePath != source || d.Mode != "copy" || d.Kind != target.Materialized || unsupported != (source == "") {
			t.Fatalf("%s: %+v", name, d)
		}
	}
	if len(r.Targets) != 1+3+4 {
		t.Fatalf("unexpected declarations:\n%s", describe(r))
	}
}

func TestDisabledAndUnsupported(t *testing.T) {
	t.Parallel()
	f := newFixture(t, nil)
	for _, text := range []string{
		strings.Replace(everything, "agent = \"codex\"", "agent = \"codex\"\nenabled = false", 1),
		everything + "primitives.instructions.enabled = false\nprimitives.skills.enabled = false\nprimitives.commands.enabled = false\n",
		everything + "[targets.codex.instances.main]\ndir = \"~/.codex\"\nprimitives.instructions.enabled = false\nprimitives.skills.enabled = false\nprimitives.commands.enabled = false\n",
		strings.Replace(everything, "agent = \"codex\"", "agent = \"claude\"", 1),
	} {
		if r := f.plan(t, text); len(r.Targets) != 0 {
			t.Fatalf("declared targets:\n%s", describe(r))
		}
	}
	_, err := f.planErr(t, everything+"primitives.instructions.render = \"import\"\n")
	if err == nil || !strings.Contains(err.Error(), "not supported") {
		t.Fatalf("import render error = %v", err)
	}
	r := f.plan(t, everything+"primitives.instructions.render = \"concat\"\n")
	if _, ok := find(r.Targets, codexHome+"/AGENTS.md"); !ok {
		t.Fatal("explicit concat render declared nothing")
	}
}

// TestSettingsNotSynced: a fragment is reported as unsupported, never merged.
func TestSettingsNotSynced(t *testing.T) {
	t.Parallel()
	c := goldenCases()[3]
	r := newFixture(t, c.env).plan(t, c.manifest)
	for _, d := range r.Targets {
		if filepath.Base(d.Path) != "config.toml" {
			continue
		}
		if d.Path != codexHome+"/config.toml" || d.Warning == "" || d.Merger != nil || d.SourcePath != "" || d.Content != nil {
			t.Fatalf("settings declared for synchronization: %+v", d)
		}
	}
	if _, ok := find(r.Targets, codexHome+"/config.toml"); !ok {
		t.Fatal("declared settings fragment not reported")
	}
}
