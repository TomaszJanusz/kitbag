// TestHomePrecedence: an explicit instance dir, then CODEX_HOME, then ~/.codex.
// CODEX_HOME never relocates the shared skills root.
func TestHomePrecedence(t *testing.T) {
	t.Parallel()
	listed := everything + "[targets.codex.instances.main]\ndir = \"~/.codex-main\"\n"
	for _, c := range []struct {
		env            map[string]string
		name, manifest string
		want           string
	}{
		{name: "default", manifest: everything, want: codexHome},
		{name: "empty variable", manifest: everything, env: map[string]string{"CODEX_HOME": ""}, want: codexHome},
		{name: "variable", manifest: everything, env: map[string]string{"CODEX_HOME": customHome}, want: customHome},
		{name: "unclean variable", manifest: everything, env: map[string]string{"CODEX_HOME": customHome + "/"}, want: customHome},
		{name: "listed", manifest: listed, env: map[string]string{"CODEX_HOME": customHome}, want: home + "/.codex-main"},
	} {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			r := newFixture(t, c.env).plan(t, c.manifest)
			if _, ok := find(r.Targets, c.want+"/AGENTS.md"); !ok {
				t.Fatalf("no AGENTS.md in %s:\n%s", c.want, describe(r))
			}
			if _, ok := find(r.Targets, sharedSkills+"/alpha"); !ok {
				t.Fatalf("skills left the shared root:\n%s", describe(r))
			}
			for _, d := range r.Targets {
				if !strings.HasPrefix(d.Path, c.want+"/") && !strings.HasPrefix(d.Path, sharedSkills+"/") {
					t.Fatalf("declaration outside %s: %s", c.want, d.Path)
				}
			}
		})
	}
}

