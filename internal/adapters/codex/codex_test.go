type goldenCase struct {
	env      map[string]string
	name     string
	manifest string
}

func goldenCases() []goldenCase {
	return []goldenCase{
		{name: "default", manifest: everything},
		{name: "codex-home", manifest: everything, env: map[string]string{"CODEX_HOME": customHome}},
		{name: "instances", manifest: everything + `
[targets.codex.instances.main]
dir = "~/.codex"
[targets.codex.instances.work]
dir = "~/.codex-work"
mode = "copy"
roots.commands = "~/work-prompts"
[targets.codex.instances.off]
dir = "~/.codex-off"
enabled = false
`, env: map[string]string{"CODEX_HOME": customHome}},
		{name: "settings", manifest: everything + `settings = "codex/config.toml"
[targets.codex.instances.main]
dir = "~/.codex"
[targets.codex.instances.plain]
dir = "~/.codex-plain"
settings = false
`},
		{name: "unimplemented", manifest: withHost + `
[agents]
dir = "agents"
[targets.codex]
agent = "codex"
primitives.instructions.enabled = false
`},
	}
}

// TestGolden pins every declaration of representative manifests: paths,
// kinds, modes, sources, instance protection, owners and generated bytes.
func TestGolden(t *testing.T) {
	t.Parallel()
	for _, c := range goldenCases() {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			golden(t, c.name+".txt", describe(newFixture(t, c.env).plan(t, c.manifest)))
		})
	}
}

// TestLegacyCompatibility compares AGENTS.md with agent-config-sync's own
// output for the shared fixture (internal/adapters/instructions/testdata/legacy).
// Only the first line, the marker, may differ.
func TestLegacyCompatibility(t *testing.T) {
	t.Parallel()
	for _, c := range []struct{ legacy, host string }{
		{"concat-host", "example"},
		{"concat-no-host", "absent"},
	} {
		t.Run(c.legacy, func(t *testing.T) {
			t.Parallel()
			legacy, err := fs.ReadFile(os.DirFS(filepath.Join(sharedFixtures, "legacy")), c.legacy+".md")
			if err != nil {
				t.Fatal(err)
			}
			marker, rest, _ := bytes.Cut(legacy, []byte("\n"))
			if !bytes.HasPrefix(marker, []byte("<!-- Managed by agent-config-sync (")) {
				t.Fatalf("legacy fixture lacks its marker: %q", marker)
			}
			want := append([]byte(instructions.Marker+"\n"), rest...)
			f := newFixture(t, nil)
			f.selected = c.host
			got, ok := find(f.plan(t, everything).Targets, codexHome+"/AGENTS.md")
			if !ok || got.Kind != target.Generated || got.Warning != "" {
				t.Fatalf("no generated AGENTS.md: %+v", got)
			}
			if !bytes.Equal(got.Content, want) {
				t.Fatalf("not byte-identical to agent-config-sync:\ngot:  %q\nwant: %q", got.Content, want)
			}
			if !instructions.Managed(got.Content) {
				t.Fatal("marker is not the first line")
			}
		})
	}
}

