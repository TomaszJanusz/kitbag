package opencode_test

import "testing"

const (
	agentHome  = "/home/user/.config/opencode"
	customHome = "/srv/custom"
)

const withHost = `schema = 1
[instructions]
source = "global/AGENTS.md"
hosts = "hosts/{host}.md"
`

const everything = withHost + `
[skills]
dirs = ["skills", "vendor"]
[commands]
dir = "commands"
per_agent.opencode = "opencode-commands"
[targets.opencode]
agent = "opencode"
`

type goldenCase struct {
	env      map[string]string
	name     string
	manifest string
}

func goldenCases() []goldenCase {
	return []goldenCase{
		{name: "default", manifest: everything},
		{name: "agents", manifest: withHost + `[agents]
dir = "agents"
per_agent.opencode = "opencode-agents"
[targets.opencode]
agent = "opencode"
`},
		{name: "opencode-home", manifest: everything, env: map[string]string{"XDG_CONFIG_HOME": customHome}},
		{name: "instances", manifest: everything + `
[targets.opencode.instances.main]
dir = "~/.opencode"
[targets.opencode.instances.work]
dir = "~/.opencode-work"
mode = "copy"
roots.commands = "~/work-prompts"
[targets.opencode.instances.off]
dir = "~/.opencode-off"
enabled = false
`, env: map[string]string{"XDG_CONFIG_HOME": customHome}},
		{name: "settings", manifest: everything + `settings = "opencode/config.toml"
[targets.opencode.instances.main]
dir = "~/.opencode"
[targets.opencode.instances.plain]
dir = "~/.opencode-plain"
settings = false
`},
		{name: "unimplemented", manifest: withHost + `
[hooks]
dir = "agents"
[targets.opencode]
agent = "opencode"
primitives.instructions.enabled = false
`},
	}
}

// TestGolden pins every declaration of representative manifests: paths,
// kinds, modes, sources, instance protection, owners and generated bytes.
func TestGolden(t *testing.T) {
	t.Parallel()
	for _, c := range goldenCases() {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			golden(t, c.name+".txt", describe(newFixture(t, c.env).plan(t, c.manifest)))
		})
	}
}
