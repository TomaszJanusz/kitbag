package gemini_test

import "testing"

const (
	agentHome    = "/home/user/.gemini"
	sharedSkills = "/home/user/.agents/skills"
	customHome   = "/srv/custom"
)

const withHost = `schema = 1
[instructions]
source = "global/AGENTS.md"
hosts = "hosts/{host}.md"
`

const everything = withHost + `
[skills]
dirs = ["skills", "vendor"]
[commands]
dir = "commands"
per_agent.gemini = "gemini-commands"
[targets.gemini]
agent = "gemini"
`

type goldenCase struct {
	env      map[string]string
	name     string
	manifest string
}

func goldenCases() []goldenCase {
	return []goldenCase{
		{name: "default", manifest: everything},
		{name: "gemini-home", manifest: everything, env: map[string]string{"GEMINI_CLI_HOME": customHome}},
		{name: "instances", manifest: everything + `
[targets.gemini.instances.main]
dir = "~/.gemini"
[targets.gemini.instances.work]
dir = "~/.gemini-work"
mode = "copy"
roots.commands = "~/work-prompts"
[targets.gemini.instances.off]
dir = "~/.gemini-off"
enabled = false
`, env: map[string]string{"GEMINI_CLI_HOME": customHome}},
		{name: "settings", manifest: everything + `settings = "gemini/config.toml"
[targets.gemini.instances.main]
dir = "~/.gemini"
[targets.gemini.instances.plain]
dir = "~/.gemini-plain"
settings = false
`},
		{name: "unimplemented", manifest: withHost + `
[agents]
dir = "agents"
[targets.gemini]
agent = "gemini"
primitives.instructions.enabled = false
`},
	}
}

// TestGolden pins every declaration of representative manifests: paths,
// kinds, modes, sources, instance protection, owners and generated bytes.
func TestGolden(t *testing.T) {
	t.Parallel()
	for _, c := range goldenCases() {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			golden(t, c.name+".txt", describe(newFixture(t, c.env).plan(t, c.manifest)))
		})
	}
}
