// Flags are registered locally, with no package globals. Update reviewed goldens:
//
//	mise exec -- go test ./internal/adapters/instructions -run '^TestGolden$' -args -update
func TestMain(m *testing.M) {
	flag.Bool("update", false, "rewrite reviewed instruction rendering goldens")
	flag.Parse()
	os.Exit(m.Run())
}

const (
	repository = "/repo"
	host       = "hosts/example.md"
	absentHost = "hosts/absent.md"
)

type goldenCase struct {
	name     string
	agent    string
	source   string
	hosts    string
	strategy instructions.Strategy
}

func goldenCases() []goldenCase {
	return []goldenCase{
		{name: "import-host", agent: "claude", hosts: host, strategy: instructions.Import},
		{name: "import-no-host", agent: "claude", hosts: absentHost, strategy: instructions.Import},
		{name: "import-override", agent: "gemini", hosts: host, strategy: instructions.Import},
		{name: "concat-host", agent: "codex", hosts: host, strategy: instructions.Concat},
		{name: "concat-no-host", agent: "codex", hosts: absentHost, strategy: instructions.Concat},
		{name: "concat-override", agent: "gemini", hosts: host, strategy: instructions.Concat},
		{name: "link", agent: "codex", strategy: instructions.Link},
		{name: "link-no-host", agent: "codex", hosts: absentHost, strategy: instructions.Link},
		{name: "link-override", agent: "gemini", strategy: instructions.Link},
		{name: "link-host", agent: "codex", hosts: host, strategy: instructions.Link},
		{name: "missing-source", agent: "codex", source: "global/absent.md", hosts: host, strategy: instructions.Concat},
	}
}

// TestGolden pins every strategy, a missing host addition and an override.
// Each <name>.txt describes the declaration; <name>.md holds generated bytes.
func TestGolden(t *testing.T) {
	t.Parallel()
	for _, c := range goldenCases() {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			h := fixtureHost(t)
			got, err := instructions.Declare(h, c.request())
			if err != nil {
				t.Fatal(err)
			}
			golden(t, c.name+".txt", describe(got))
			if got.Target.Kind == target.Generated && got.Target.Warning == "" {
				golden(t, c.name+".md", string(got.Target.Content))
			}
		})
	}
}

func (c goldenCase) request() instructions.Request {
	source := c.source
	if source == "" {
		source = "global/AGENTS.md"
	}
	return instructions.Request{
		Instructions: &manifest.Instructions{
			Source:   source,
			Hosts:    c.hosts,
			PerAgent: map[string]string{"gemini": "agents/override.md"},
		},
		Repository: repository,
		Path:       "/home/user/." + c.agent + "/INSTRUCTIONS.md",
		Agent:      c.agent,
		Strategy:   c.strategy,
		Owners:     []state.Owner{{Primitive: "instructions", AgentInstance: c.agent + ":main"}},
	}
}

func describe(r instructions.Result) string {
	d := r.Target
	var lines []string
	for _, line := range [][2]string{
		{"kind", string(d.Kind)},
		{"path", d.Path},
		{"source", d.SourcePath},
		{"backup", string(d.Backup)},
		{"warning", d.Warning},
	} {
		if line[1] != "" {
			lines = append(lines, line[0]+": "+line[1])
		}
	}
	for _, owner := range d.Owners {
		lines = append(lines, "owner: "+owner.Primitive+" "+owner.AgentInstance)
	}
	for _, warning := range r.Warnings {
		lines = append(lines, "non-blocking warning: "+warning)
	}
	return strings.Join(lines, "\n") + "\n"
}

// fixtureHost copies testdata/repo into an in-memory host at /repo.
func fixtureHost(t *testing.T) *fake.Host {
	t.Helper()
	h := fake.New()
	root := os.DirFS(filepath.Join("testdata", "repo"))
	err := fs.WalkDir(root, ".", func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		data, err := fs.ReadFile(root, path)
		if err != nil {
			return err
		}
		writeFile(t, h, filepath.Join(repository, filepath.FromSlash(path)), data)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return h
}

func writeFile(t *testing.T, h *fake.Host, name string, data []byte) {
	t.Helper()
	if err := h.MkdirAll(filepath.Dir(name), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := h.WriteAtomic(name, data, 0o600); err != nil {
		t.Fatal(err)
	}
}

func golden(t *testing.T, name, got string) {
	t.Helper()
	dir := filepath.Join("testdata", "golden")
	if flag.Lookup("update").Value.String() == "true" {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(got), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	want, err := fs.ReadFile(os.DirFS(dir), name)
	if err != nil {
		t.Fatal(err)
	}
	if got != string(want) {
		t.Fatalf("golden mismatch for %s:\ngot:\n%q\nwant:\n%q", name, got, want)
	}
}
